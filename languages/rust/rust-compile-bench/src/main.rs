//! Compares how long types using `#[derive(ArriModel)]` take to compile vs `#[derive(Serialize, Deserialize)]`.
//!
//! ```bash
//! cargo run -p arri-compile-bench --release -- [--copies 50] [--iterations 5] [--clean-iterations 2]
//! ```
//!
//! Three otherwise identical crates are generated under `target/compile-bench`:
//!
//! - `baseline`: the types with no derives (measures the cost of the compiler / cargo themselves)
//! - `arri`: the types with `#[derive(ArriModel)]`, round tripped through `arri::json`
//! - `serde`: the types with `#[derive(Serialize, Deserialize)]`, round tripped through `serde_json`
//!
//! Each crate contains `--copies` copies of a set of 6 types (structs, a plain enum, an internally
//! tagged union, and a large object that contains the others). The encode / decode methods of both
//! libraries are generic over the format, so they're only compiled when they're used. Each crate
//! therefore round trips its types through JSON so that the generated code is actually compiled.
//!
//! Measurements:
//!
//! - `check`, `build (debug)`, `build (release)`: rebuilding only the generated crate (its
//!   dependencies are already compiled). Incremental compilation is disabled so that every run does
//!   the same amount of work.
//! - `clean build (debug)`: building the crate and all of its dependencies from scratch
//!
//! The "derive cost" columns subtract the baseline from each measurement.
//!
//! Any `rustc` wrapper (such as sccache) is disabled while measuring, since a compiler cache would
//! return cached results rather than compiling.

use std::{
    fmt::Write as _,
    fs,
    path::{Path, PathBuf},
    process::Command,
    time::{Duration, Instant},
};

#[derive(Clone, Copy, PartialEq)]
enum Variant {
    Baseline,
    Arri,
    Serde,
}

const VARIANTS: [Variant; 3] = [Variant::Baseline, Variant::Arri, Variant::Serde];

impl Variant {
    fn name(self) -> &'static str {
        match self {
            Variant::Baseline => "baseline",
            Variant::Arri => "arri",
            Variant::Serde => "serde",
        }
    }

    fn dependencies(self, arri_path: &Path) -> String {
        match self {
            Variant::Baseline => String::new(),
            Variant::Arri => format!(
                "arri = {{ path = {:?}, default-features = false, features = [\"derive\"] }}\n",
                arri_path.display().to_string()
            ),
            Variant::Serde => {
                "serde = { version = \"1\", features = [\"derive\"] }\nserde_json = \"1\"\n"
                    .to_string()
            }
        }
    }

    fn source(self, copies: usize) -> String {
        let (derive, nullable, bio_attr, union_attr) = match self {
            Variant::Baseline => ("", "Option", "", ""),
            Variant::Arri => (
                "#[derive(arri::ArriModel)]",
                "arri::Nullable",
                "",
                "#[arri(tag_key = \"type\")]",
            ),
            Variant::Serde => (
                "#[derive(serde::Serialize, serde::Deserialize)]",
                "Option",
                "#[serde(default, skip_serializing_if = \"Option::is_none\")]",
                "#[serde(tag = \"type\")]",
            ),
        };
        let mut out = String::from(
            "#![allow(dead_code)]\n//! Generated by arri-compile-bench. Do not edit.\n\nuse std::collections::BTreeMap;\n\n",
        );
        for i in 0..copies {
            let round_trip = match self {
                Variant::Baseline => "input.to_string()".to_string(),
                Variant::Arri => format!(
                    "let value: Report{i} = arri::json::from_str(input).unwrap();\n    arri::json::to_string(&value).unwrap()"
                ),
                Variant::Serde => format!(
                    "let value: Report{i} = serde_json::from_str(input).unwrap();\n    serde_json::to_string(&value).unwrap()"
                ),
            };
            let _ = write!(
                out,
                r#"{derive}
pub enum Role{i} {{
    Standard,
    Admin,
    Moderator,
}}

{derive}
pub struct Settings{i} {{
    pub theme: String,
    pub notifications: bool,
    pub limits: BTreeMap<String, u32>,
}}

{derive}
pub struct User{i} {{
    pub id: String,
    pub name: String,
    pub email: {nullable}<String>,
    {bio_attr}
    pub bio: Option<String>,
    pub age: u32,
    pub is_admin: bool,
    pub score: f64,
    pub role: Role{i},
    pub tags: Vec<String>,
    pub created_at: String,
    pub settings: Settings{i},
}}

{derive}
{union_attr}
pub enum Event{i} {{
    Created {{ user: User{i} }},
    Renamed {{ id: String, old_name: String, new_name: String }},
    Deleted {{ id: String, deleted_at: String }},
}}

{derive}
pub struct Section{i} {{
    pub heading: String,
    pub body: String,
    pub order: u16,
    pub is_collapsed: bool,
    pub weight: f64,
    pub attributes: BTreeMap<String, String>,
}}

{derive}
pub struct Report{i} {{
    pub id: String,
    pub title: String,
    pub summary: String,
    pub created_at: String,
    pub updated_at: {nullable}<String>,
    pub version: u32,
    pub priority: u8,
    pub offset: i16,
    pub ratio: f32,
    pub score: f64,
    pub is_public: bool,
    pub is_archived: bool,
    pub owner: User{i},
    pub tags: Vec<String>,
    pub counters: BTreeMap<String, u32>,
    pub sections: Vec<Section{i}>,
    pub authors: Vec<User{i}>,
    pub latest_event: Event{i},
}}

pub fn round_trip_{i}(input: &str) -> String {{
    {round_trip}
}}

"#
            );
        }
        out
    }
}

struct Options {
    copies: usize,
    iterations: usize,
    clean_iterations: usize,
}

fn parse_options() -> Options {
    let mut options = Options {
        copies: 50,
        iterations: 5,
        clean_iterations: 2,
    };
    let mut args = std::env::args().skip(1);
    while let Some(arg) = args.next() {
        let mut value = || -> usize {
            args.next()
                .and_then(|v| v.parse().ok())
                .unwrap_or_else(|| panic!("{arg} expects a number"))
        };
        match arg.as_str() {
            "--copies" => options.copies = value(),
            "--iterations" => options.iterations = value(),
            "--clean-iterations" => options.clean_iterations = value(),
            "--help" | "-h" => {
                println!(
                    "usage: arri-compile-bench [--copies N] [--iterations N] [--clean-iterations N]"
                );
                std::process::exit(0);
            }
            other => panic!("unknown argument {other}"),
        }
    }
    options
}

fn cargo(dir: &Path, args: &[&str]) -> Duration {
    let start = Instant::now();
    let output = Command::new(std::env::var("CARGO").unwrap_or_else(|_| "cargo".into()))
        .args(args)
        .arg("--quiet")
        .current_dir(dir)
        .env("CARGO_INCREMENTAL", "0")
        // compiler caches (such as sccache) would return cached results instead of compiling
        .env("RUSTC_WRAPPER", "")
        .env("RUSTC_WORKSPACE_WRAPPER", "")
        .output()
        .expect("failed to run cargo");
    let elapsed = start.elapsed();
    if !output.status.success() {
        panic!(
            "`cargo {}` failed in {}:\n{}",
            args.join(" "),
            dir.display(),
            String::from_utf8_lossy(&output.stderr)
        );
    }
    elapsed
}

/// Rewrite the source file so that cargo considers the crate dirty
fn touch(file: &Path) {
    let contents = fs::read(file).unwrap();
    fs::write(file, contents).unwrap();
}

fn median(mut values: Vec<Duration>) -> Duration {
    values.sort();
    values[values.len() / 2]
}

fn seconds(duration: Duration) -> String {
    format!("{:.2}s", duration.as_secs_f64())
}

fn difference(value: Duration, baseline: Duration) -> String {
    format!("+{:.2}s", value.as_secs_f64() - baseline.as_secs_f64())
}

fn main() {
    let options = parse_options();
    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let workspace = manifest_dir.parent().unwrap().to_path_buf();
    let arri_path = fs::canonicalize(workspace.join("rust-core")).unwrap();
    let root = workspace.join("target").join("compile-bench");

    println!(
        "Generating {} copies of 6 types ({} types per crate)",
        options.copies,
        options.copies * 6
    );
    let mut crates = Vec::new();
    for variant in VARIANTS {
        let dir = root.join(variant.name());
        fs::create_dir_all(dir.join("src")).unwrap();
        // the empty [workspace] table keeps these crates out of the parent workspace
        fs::write(
            dir.join("Cargo.toml"),
            format!(
                "[package]\nname = \"bench_{}\"\nversion = \"0.0.0\"\nedition = \"2024\"\npublish = false\n\n[workspace]\n\n[dependencies]\n{}",
                variant.name(),
                variant.dependencies(&arri_path)
            ),
        )
        .unwrap();
        fs::write(dir.join("src/lib.rs"), variant.source(options.copies)).unwrap();
        crates.push((variant, dir));
    }

    let modes: [(&str, &[&str]); 3] = [
        ("check", &["check"]),
        ("build (debug)", &["build"]),
        ("build (release)", &["build", "--release"]),
    ];
    // [variant][mode]
    let mut results: Vec<Vec<Duration>> = Vec::new();
    for (variant, dir) in &crates {
        let lib = dir.join("src/lib.rs");
        let mut variant_results = Vec::new();
        for (label, args) in modes {
            // compile the dependencies first so that only the generated crate is measured
            cargo(dir, args);
            let mut times = Vec::new();
            for _ in 0..options.iterations {
                touch(&lib);
                times.push(cargo(dir, args));
            }
            let time = median(times);
            println!("{:<9} {:<16} {}", variant.name(), label, seconds(time));
            variant_results.push(time);
        }
        let mut clean_times = Vec::new();
        for _ in 0..options.clean_iterations {
            let _ = fs::remove_dir_all(dir.join("target"));
            clean_times.push(cargo(dir, &["build"]));
        }
        if !clean_times.is_empty() {
            let time = median(clean_times);
            println!(
                "{:<9} {:<16} {}",
                variant.name(),
                "clean build",
                seconds(time)
            );
            variant_results.push(time);
        }
        results.push(variant_results);
    }

    let mut labels: Vec<&str> = modes.iter().map(|(label, _)| *label).collect();
    if options.clean_iterations > 0 {
        labels.push("clean build (debug, including dependencies)");
    }
    println!();
    println!(
        "| {} types | baseline | arri | serde | arri (derive cost) | serde (derive cost) |",
        options.copies * 6
    );
    println!("| --- | --- | --- | --- | --- | --- |");
    for (index, label) in labels.iter().enumerate() {
        let baseline = results[0][index];
        let arri = results[1][index];
        let serde = results[2][index];
        println!(
            "| {label} | {} | {} | {} | {} | {} |",
            seconds(baseline),
            seconds(arri),
            seconds(serde),
            difference(arri, baseline),
            difference(serde, baseline)
        );
    }
}
